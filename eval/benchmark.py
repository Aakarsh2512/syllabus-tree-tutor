def ask_json(prompt: str) -> dict:
    """One JSON-constrained request to the local model."""
    payload = {
        "model": config.OLLAMA_MODEL,
        "prompt": prompt,
        "stream": False,
        "format": "json",
        "options": {"temperature": 0.3, "num_predict": 300},
    }
    request = urllib.request.Request(
        config.OLLAMA_URL + "/api/generate",
        data=json.dumps(payload).encode("utf-8"),
        headers={"Content-Type": "application/json"},
    )
    with urllib.request.urlopen(request, timeout=config.OLLAMA_TIMEOUT) as response:
        body = json.loads(response.read().decode("utf-8"))
    return json.loads(body.get("response", "{}"))


def usable_passage(text: str) -> bool:
    """Skip passages that are mostly code, tables or references."""
    if len(text) < 400:
        return False
    letters = 0
    for character in text:
        if character.isalpha():
            letters = letters + 1
    if letters < 0.6 * len(text):
        return False
    if text.count("[") > 12 or text.count("http") > 3:
        return False
    return True


SPECIFIC_PROMPT = """Below is one passage from a document.

Write ONE question that can be answered only from this passage - not from general knowledge.
Then copy the shortest exact phrase from the passage (2 to 8 words) that answers it.
Copy the phrase character for character.

Reply as JSON: {{"question": "...", "answer_phrase": "..."}}

PASSAGE:
{passage}
"""

BROAD_PROMPT = """Below are {count} passages from different parts of one document.

Write ONE question that a reader could only answer fully by combining information from all
{count} passages. Make it specific to this document's actual subject matter. Do not ask a
generic question such as "what is this document about", do not quote the passages, and do not
mention the word "passage".

Reply as JSON with a single key "question".

{passages}
"""


def phrase_in(phrase: str, text: str) -> bool:
    return normalize(phrase) != "" and normalize(phrase) in normalize(text)


def spread(phrases: list[str], leaves: list[dict]) -> tuple[int, int]:
    """(most phrases in any one chunk, fewest chunks that hold them all)."""
    texts = []
    for leaf in leaves:
        texts.append(normalize(leaf["text"]))

    most = 0
    for text in texts:
        count = 0
        for phrase in phrases:
            if normalize(phrase) in text:
                count = count + 1
        if count > most:
            most = count

    remaining = set()
    for phrase in phrases:
        remaining.add(normalize(phrase))
    used = 0
    while len(remaining) > 0:
        best_text = ""
        best_gain = 0
        for text in texts:
            gain = 0
            for phrase in remaining:
                if phrase in text:
                    gain = gain + 1
            if gain > best_gain:
                best_gain = gain
                best_text = text
        if best_gain == 0:
            break
        used = used + 1
        still = set()
        for phrase in remaining:
            if phrase not in best_text:
                still.add(phrase)
        remaining = still
    return most, used


def make_specific(leaves: list[dict], rng: random.Random, used: set) -> dict:
    candidates = []
    for index in range(len(leaves)):
        if index not in used and usable_passage(leaves[index]["text"]):
            candidates.append(index)
    if len(candidates) == 0:
        return None

    for attempt in range(ATTEMPTS_PER_QUESTION):
        index = rng.choice(candidates)
        passage = leaves[index]["text"]
        try:
            reply = ask_json(SPECIFIC_PROMPT.format(passage=passage))
        except Exception as error:
            log("      model error: " + str(error))
            continue
        question = str(reply.get("question", "")).strip()
        phrase = str(reply.get("answer_phrase", "")).strip()
        words = len(phrase.split())
        if not question.endswith("?") or words < 2 or words > 10:
            continue
        if not phrase_in(phrase, passage):
            continue
        used.add(index)
        return {"category": "specific", "question": question, "evidence_any": [phrase],
                "source_chunk": leaves[index]["id"]}
    return None


_phrase_index = {}


def phrase_index(leaves: list[dict]):
    """TF-IDF over the document's chunks, fitted once per document."""
    key = leaves[0]["source"] if len(leaves) > 0 else ""
    if key not in _phrase_index:
        from sklearn.feature_extraction.text import TfidfVectorizer
        texts = []
        for leaf in leaves:
            texts.append(leaf["text"])
        vectorizer = TfidfVectorizer(ngram_range=(2, 3), stop_words="english",
                                     token_pattern=r"(?u)\b[A-Za-z][A-Za-z0-9]+\b",
                                     min_df=1)
        matrix = vectorizer.fit_transform(texts)
        document_counts = np.asarray((matrix > 0).sum(axis=0)).ravel()
        _phrase_index[key] = (vectorizer.get_feature_names_out(), matrix, document_counts)
    return _phrase_index[key]


def distinctive_phrase(leaves: list[dict], index: int) -> str:
    """The highest-weighted phrase of this chunk that is rare in the document
    (in at most two chunks) and appears in the chunk word for word."""
    names, matrix, document_counts = phrase_index(leaves)
    row = matrix[index].toarray().ravel()
    order = np.argsort(row)[::-1]
    for position in order[:60]:
        if row[position] <= 0.0:
            break
        if document_counts[position] > 2:
            continue
        phrase = names[position]
        if phrase_in(phrase, leaves[index]["text"]):
            return phrase
    return ""


def make_broad(leaves: list[dict], rng: random.Random) -> dict:
    usable = []
    for index in range(len(leaves)):
        if usable_passage(leaves[index]["text"]):
            usable.append(index)
    if len(usable) < 8:
        return None

    for attempt in range(ATTEMPTS_PER_QUESTION):
        # One passage from each quarter of the document, so the question has
        # to span it rather than one section.
        picks = []
        quarter = len(usable) // 4
        for part in range(4):
            section = usable[part * quarter:(part + 1) * quarter] if part < 3 else usable[3 * quarter:]
            picks.append(rng.choice(section))

        verified = []
        for index in picks:
            phrase = distinctive_phrase(leaves, index)
            if phrase != "" and phrase not in verified:
                verified.append(phrase)
        if len(verified) < 3:
            continue

        # Check the spread before spending any model time on this sample.
        most, fewest = spread(verified, leaves)
        if most >= len(verified) or fewest < MIN_SPREAD:
            continue

        blocks = []
        for number in range(len(picks)):
            blocks.append("PASSAGE " + str(number + 1) + ":\n" + leaves[picks[number]]["text"])
        try:
            reply = ask_json(BROAD_PROMPT.format(count=len(picks), passages="\n\n".join(blocks)))
        except Exception as error:
            log("      model error: " + str(error))
            continue

        question = str(reply.get("question", "")).strip()
        if not question.endswith("?") or len(question.split()) < 6:
            continue
        leaked = 0
        for phrase in verified:
            if phrase_in(phrase, question):
                leaked = leaked + 1
        if leaked >= 2:
            continue                      # the question gives the answer away

        return {"category": "broad", "question": question, "evidence_all": verified,
                "source_chunks": [leaves[i]["id"] for i in picks],
                "max_in_one_leaf": most, "min_leaves_to_cover": fewest}
    return None


def generate_questions() -> None:
    log("questions")
    QUESTIONS_DIR.mkdir(parents=True, exist_ok=True)
    for document in load_manifest():
        path = QUESTIONS_DIR / (document["id"] + ".jsonl")
        if path.exists():
            log("  " + document["id"] + " already has questions")
            continue

        leaves = leaves_for(document["id"])
        rng = random.Random(document["id"])
        items = []
        used = set()

        log("  " + document["id"] + ": specific questions")
        for number in range(SPECIFIC_PER_DOC):
            item = make_specific(leaves, rng, used)
            if item is not None:
                items.append(item)
                log("    + " + item["question"][:90])

        log("  " + document["id"] + ": broad questions")
        for number in range(BROAD_PER_DOC):
            item = make_broad(leaves, rng)
            if item is not None:
                items.append(item)
                log("    + " + item["question"][:90] + "  (spread " + str(item["min_leaves_to_cover"]) + ")")

        with open(path, "w", encoding="utf-8") as handle:
            for number in range(len(items)):
                items[number]["id"] = document["id"] + "-" + str(number + 1).zfill(2)
                handle.write(json.dumps(items[number], ensure_ascii=False) + "\n")
        log("  " + document["id"] + ": kept " + str(len(items)) + " questions")


# -------------------------------------------------------------------- run --

def score(item: dict, hits: list[dict]) -> float:
    texts = []
    for hit in hits:
        texts.append(normalize(hit["text"]))
    if item["category"] == "specific":
        for text in texts:
            if normalize(item["evidence_any"][0]) in text:
                return 1.0
        return 0.0
    found = 0
    for phrase in item["evidence_all"]:
        for text in texts:
            if normalize(phrase) in text:
                found = found + 1
                break
    return found / len(item["evidence_all"])


def paired_interval(differences: list[float], rng: np.random.Generator) -> tuple:
    values = np.asarray(differences, dtype=float)
    if len(values) == 0:
        return 0.0, 0.0, 0.0
    means = []
    for sample in range(BOOTSTRAP_SAMPLES):
        picks = rng.integers(0, len(values), len(values))
        means.append(float(values[picks].mean()))
    return float(values.mean()), float(np.percentile(means, 2.5)), float(np.percentile(means, 97.5))


def run() -> None:
    log("run")
    documents = load_manifest()
    methods = [("flat", "ext", "flat"), ("tree_ext", "ext", "tree"),
               ("tree_ext_fine", "extfine", "tree"), ("tree_llm", "llm", "tree")]

    rows = []
    for document in documents:
        path = QUESTIONS_DIR / (document["id"] + ".jsonl")
        if not path.exists():
            continue
        items = []
        with open(path, "r", encoding="utf-8") as handle:
            for line in handle:
                if line.strip() != "":
                    items.append(json.loads(line))

        for name, variant, mode in methods:
            identifier = corpus_id(document["id"], variant)
            if not store.index_exists(identifier):
                continue
            for budget in BUDGETS:
                for item in items:
                    found = retrieve.search(item["question"], mode=mode, top_k=budget,
                                            corpus_id=identifier)
                    rows.append({
                        "document": document["id"], "genre": document["genre"],
                        "question": item["id"], "category": item["category"],
                        "method": name, "k": budget,
                        "score": score(item, found["hits"]),
                        "summaries": found["trace"]["summary_hits"],
                    })

    if len(rows) == 0:
        log("nothing to score yet")
        return

    rng = np.random.default_rng(7)
    summary = {"questions": {}, "by_budget": [], "by_genre": [], "comparisons": []}

    counted = {}
    for row in rows:
        if row["method"] == "flat" and row["k"] == BUDGETS[0]:
            counted[row["category"]] = counted.get(row["category"], 0) + 1
    summary["questions"] = counted

    def mean_of(selection):
        if len(selection) == 0:
            return None
        total = 0.0
        for row in selection:
            total = total + row["score"]
        return round(total / len(selection), 3)

    present_methods = []
    for name, variant, mode in methods:
        for row in rows:
            if row["method"] == name:
                present_methods.append(name)
                break

    categories = []
    for row in rows:
        if row["category"] not in categories:
            categories.append(row["category"])

    for category in categories:
        for budget in BUDGETS:
            entry = {"category": category, "k": budget}
            for name in present_methods:
                selection = [r for r in rows if r["method"] == name and r["k"] == budget
                             and r["category"] == category]
                entry[name] = mean_of(selection)
                summaries = [r["summaries"] for r in selection]
                entry[name + "_summaries"] = round(float(np.mean(summaries)), 2) if summaries else None
            summary["by_budget"].append(entry)

            flat_scores = {}
            for r in rows:
                if r["method"] == "flat" and r["k"] == budget and r["category"] == category:
                    flat_scores[r["question"]] = r["score"]
            for name in present_methods:
                if name == "flat":
                    continue
                differences = []
                for r in rows:
                    if r["method"] == name and r["k"] == budget and r["category"] == category:
                        if r["question"] in flat_scores:
                            differences.append(r["score"] - flat_scores[r["question"]])
                mean, low, high = paired_interval(differences, rng)
                summary["comparisons"].append({
                    "category": category, "k": budget, "method": name, "vs": "flat",
                    "difference": round(mean, 3), "ci_low": round(low, 3), "ci_high": round(high, 3),
                    "n": len(differences),
                })

    genres = []
    for document in documents:
        if document["genre"] not in genres:
            genres.append(document["genre"])
    for genre in genres:
        for category in categories:
            entry = {"genre": genre, "category": category, "k": 6}
            for name in present_methods:
                selection = [r for r in rows if r["method"] == name and r["k"] == 6
                             and r["category"] == category and r["genre"] == genre]
                entry[name] = mean_of(selection)
                entry["n"] = len(selection)
            summary["by_genre"].append(entry)

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    with open(OUT_DIR / "results.json", "w", encoding="utf-8") as handle:
        json.dump({"summary": summary, "rows": rows}, handle, ensure_ascii=False, indent=1)
    write_report(summary, present_methods)
    log("wrote eval/bench/results.json and results.md")


def write_report(summary: dict, methods: list[str]) -> None:
    def cell(value):
        return "-" if value is None else "%.3f" % value

    lines = ["# Benchmark: normal RAG vs the RAPTOR tree", ""]
    lines.append("Questions: " + json.dumps(summary["questions"]) + ", generated and verified "
                 "as described in `eval/benchmark.py`.")
    lines.append("")
    lines.append("## Score by context budget")
    lines.append("")
    header = "| Questions | Passages | " + " | ".join("`" + m + "`" for m in methods) + " |"
    lines.append(header)
    lines.append("|" + "---|" * (2 + len(methods)))
    for entry in summary["by_budget"]:
        values = []
        for m in methods:
            values.append(cell(entry.get(m)))
        lines.append("| " + entry["category"] + " | " + str(entry["k"]) + " | " + " | ".join(values) + " |")
    lines.append("")
    lines.append("## Difference from flat RAG, with 95% bootstrap intervals")
    lines.append("")
    lines.append("| Questions | Passages | Method | Difference | 95% interval | Questions |")
    lines.append("|---|---|---|---|---|---|")
    for c in summary["comparisons"]:
        lines.append("| %s | %d | `%s` | %+.3f | [%+.3f, %+.3f] | %d |" % (
            c["category"], c["k"], c["method"], c["difference"], c["ci_low"], c["ci_high"], c["n"]))
    lines.append("")
    lines.append("An interval that excludes zero is a difference unlikely to be noise.")
    lines.append("")
    lines.append("## By document genre (6 passages)")
    lines.append("")
    lines.append("| Genre | Questions | n | " + " | ".join("`" + m + "`" for m in methods) + " |")
    lines.append("|" + "---|" * (3 + len(methods)))
    for entry in summary["by_genre"]:
        values = []
        for m in methods:
            values.append(cell(entry.get(m)))
        lines.append("| " + entry["genre"] + " | " + entry["category"] + " | " + str(entry.get("n", 0))
                     + " | " + " | ".join(values) + " |")
    (OUT_DIR / "results.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


# ---------------------------------------------------------------- QuALITY --
# Human-written multiple-choice questions over long articles (Pang et al., 2022),
# the benchmark the RAPTOR paper reports on. Roughly half the questions are
# marked "difficult": annotators could not answer them by skimming, so they
# need the whole text. That is exactly the case the tree is meant to help.

QUALITY_DIR = BENCH_DATA / "quality"
QUALITY_BUDGET = 6          # ~1,800 tokens of context, near the paper's 2,000
QUALITY_ARTICLES = 6
QUALITY_PER_ARTICLE = 10    # half difficult, half not, where available
ANSWERS_PATH = OUT_DIR / "quality_answers.jsonl"
LETTERS = ["A", "B", "C", "D"]


def quality_articles() -> list[dict]:
    """A fixed, mixed-source selection of dev-set articles and their questions."""
    path = QUALITY_DIR / "QuALITY.v1.0.1.htmlstripped.dev"
    rows = []
    with open(path, "r", encoding="utf-8") as handle:
        for line in handle:
            if line.strip() != "":
                rows.append(json.loads(line))

    by_article = {}
    order = []
    for row in rows:
        key = row["article_id"]
        if key not in by_article:
            by_article[key] = {"article_id": key, "title": row["title"],
                               "source": row["source"], "text": row["article"],
                               "questions": []}
            order.append(key)
        seen = set()
        for existing in by_article[key]["questions"]:
            seen.add(existing["question"].strip().lower())
        for question in row["questions"]:
            if question["question"].strip().lower() not in seen:
                by_article[key]["questions"].append(question)
                seen.add(question["question"].strip().lower())

    wanted = {"Gutenberg": 3, "Slate": 2, "misc-longshort": 1}
    chosen = []
    taken = {}
    for key in sorted(order):
        article = by_article[key]
        source = article["source"]
        if taken.get(source, 0) < wanted.get(source, 0):
            chosen.append(article)
            taken[source] = taken.get(source, 0) + 1
        if len(chosen) >= QUALITY_ARTICLES:
            break

    for article in chosen:
        rng = random.Random(article["article_id"])
        hard = [q for q in article["questions"] if q.get("difficult") == 1]
        easy = [q for q in article["questions"] if q.get("difficult") != 1]
        rng.shuffle(hard)
        rng.shuffle(easy)
        half = QUALITY_PER_ARTICLE // 2
        picked = hard[:half] + easy[:half]
        if len(picked) < QUALITY_PER_ARTICLE:
            extra = hard[half:] + easy[half:]
            picked = picked + extra[:QUALITY_PER_ARTICLE - len(picked)]
        article["questions"] = picked
    return chosen


def article_leaves(article: dict) -> list[dict]:
    """Chunk a plain-text article exactly as a one-page PDF would be chunked."""
    pages = [{"page": 1, "text": ingest.clean_text(article["text"])}]
    leaves = []
    counter = 0
    for record in ingest.chunk_document(pages, article["title"]):
        counter = counter + 1
        leaves.append({"id": "L" + str(counter).zfill(4), "level": 0, "kind": "leaf",
                       "text": record["text"], "source": record["source"],
                       "pages": record["pages"], "children": [], "member_count": 1})
    return leaves


def quality_build(variant: str) -> None:
    log("quality build " + variant)
    for article in quality_articles():
        identifier = "q-" + article["article_id"] + "__" + variant
        if store.index_exists(identifier):
            log("  " + identifier + " already built")
            continue
        leaves = article_leaves(article)
        provider = "offline" if variant == "ext" else llm.provider()
        config.CLUSTER_TARGET_SIZE = 0
        log("  building " + identifier + " (" + article["title"][:40] + ") from "
            + str(len(leaves)) + " chunks, summaries by " + provider)
        started = time.time()

        def progress(message: str) -> None:
            if message.strip().startswith("summary"):
                log("    " + message.strip())

        nodes, embeddings = tree.build_tree(leaves, embedder(), progress=progress,
                                            use_provider=provider)
        stats = tree.tree_stats(nodes)
        store.save_index(nodes, embeddings, {
            "name": article["title"], "variant": variant, "summary_provider": provider,
            "stats": stats, "build_seconds": round(time.time() - started, 1),
        }, corpus_id=identifier)
        log("  built " + identifier + ": " + json.dumps(stats["nodes_per_level"]))


MC_PROMPT = """Answer the multiple-choice question about a story or article, using the
passages from it below. Pick the single best option.

{passages}

QUESTION: {question}
A. {a}
B. {b}
C. {c}
D. {d}

Reply as JSON with a single key "answer" whose value is exactly one letter."""


def answer_letter(reply: dict) -> str:
    value = str(reply.get("answer", "")).strip().upper()
    for character in value:
        if character in LETTERS:
            return character
    return ""


def load_answers() -> dict:
    answers = {}
    if ANSWERS_PATH.exists():
        with open(ANSWERS_PATH, "r", encoding="utf-8") as handle:
            for line in handle:
                if line.strip() != "":
                    row = json.loads(line)
                    answers[(row["question_id"], row["method"], row["k"])] = row
    return answers


def quality_run(methods: list[str]) -> None:
    log("quality run " + ", ".join(methods))
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    answers = load_answers()
    articles = quality_articles()

    total = 0
    for article in articles:
        total = total + len(article["questions"])
    done = 0

    for method in methods:
        variant = "llm" if method == "tree_llm" else "ext"
        mode = "flat" if method == "flat" else "tree"
        for article in articles:
            identifier = "q-" + article["article_id"] + "__" + variant
            if not store.index_exists(identifier):
                log("  skip " + identifier + ": not built")
                continue
            for question in article["questions"]:
                key = (question["question_unique_id"], method, QUALITY_BUDGET)
                done = done + 1
                if key in answers:
                    continue
                found = retrieve.search(question["question"], mode=mode,
                                        top_k=QUALITY_BUDGET, corpus_id=identifier)
                blocks = []
                used = 0
                for hit in found["hits"]:
                    text = hit["text"]
                    if used + len(text) > 8000:
                        text = text[:max(0, 8000 - used)]
                    used = used + len(text)
                    blocks.append("[" + str(hit["rank"]) + "] " + text)
                options = question["options"]
                prompt = MC_PROMPT.format(passages="\n\n".join(blocks),
                                          question=question["question"],
                                          a=options[0], b=options[1], c=options[2], d=options[3])
                started = time.time()
                try:
                    letter = answer_letter(ask_json(prompt))
                except Exception as error:
                    log("    model error: " + str(error))
                    continue
                gold = LETTERS[question["gold_label"] - 1]
                row = {
                    "question_id": question["question_unique_id"],
                    "article_id": article["article_id"], "source": article["source"],
                    "method": method, "k": QUALITY_BUDGET,
                    "difficult": question.get("difficult") == 1,
                    "answer": letter, "gold": gold, "correct": letter == gold,
                    "summaries": found["trace"]["summary_hits"],
                    "seconds": round(time.time() - started, 1),
                }
                answers[key] = row
                with open(ANSWERS_PATH, "a", encoding="utf-8") as handle:
                    handle.write(json.dumps(row) + "\n")
                log("    [%s %d/%d] %s gold %s -> %s%s" % (
                    method, done, total * len(methods), question["question_unique_id"][-12:],
                    gold, letter or "?", "  correct" if letter == gold else ""))
    quality_report()


def mcnemar(right_a: list, right_b: list) -> tuple:
    """Exact two-sided test on just the questions the two methods disagree about.

    Questions both got right, or both got wrong, carry no information about
    which is better; only the disagreements do.
    """
    only_a = 0
    only_b = 0
    for index in range(len(right_a)):
        if right_a[index] and not right_b[index]:
            only_a = only_a + 1
        if right_b[index] and not right_a[index]:
            only_b = only_b + 1
    total = only_a + only_b
    smaller = min(only_a, only_b)
    tail = 0.0
    for count in range(0, smaller + 1):
        tail = tail + math.comb(total, count) * (0.5 ** total) if total > 0 else 0.0
    return only_a, only_b, min(1.0, 2 * tail) if total > 0 else 1.0


def quality_report() -> None:
    answers = load_answers()
    if len(answers) == 0:
        return
    by_method = {}
    for row in answers.values():
        by_method.setdefault(row["method"], {})[row["question_id"]] = row

    lines = ["# QuALITY: normal RAG vs the RAPTOR tree", ""]
    lines.append("Human-written multiple-choice questions (4 options, so guessing scores 25%). "
                 + str(QUALITY_BUDGET) + " passages of context per question.")
    lines.append("")
    lines.append("| Method | All | Difficult | Not difficult | Questions | Summaries used / question |")
    lines.append("|---|---|---|---|---|---|")
    summary = {}
    for method in ["flat", "tree_ext", "tree_llm"]:
        if method not in by_method:
            continue
        rows = list(by_method[method].values())

        def accuracy(selection):
            if len(selection) == 0:
                return None
            right = 0
            for row in selection:
                if row["correct"]:
                    right = right + 1
            return right / len(selection)

        everything = accuracy(rows)
        hard = accuracy([r for r in rows if r["difficult"]])
        easy = accuracy([r for r in rows if not r["difficult"]])
        used = float(np.mean([r["summaries"] for r in rows]))
        summary[method] = {"all": everything, "difficult": hard, "not_difficult": easy,
                           "n": len(rows), "summaries": round(used, 2)}

        def pct(value):
            return "-" if value is None else "%.1f%%" % (100 * value)

        lines.append("| `%s` | %s | %s | %s | %d | %.2f |" % (
            method, pct(everything), pct(hard), pct(easy), len(rows), used))

    rng = np.random.default_rng(11)
    lines.append("")
    lines.append("## Paired comparison with flat RAG, same questions")
    lines.append("")
    lines.append("| Method | Difference | 95% interval | Exact p | Both right | Only tree right | Only flat right | Both wrong |")
    lines.append("|---|---|---|---|---|---|---|---|")
    comparisons = []
    for method in ["tree_ext", "tree_llm"]:
        if method not in by_method or "flat" not in by_method:
            continue
        differences = []
        tree_right = []
        flat_right = []
        counts = {"both": 0, "tree": 0, "flat": 0, "neither": 0}
        for question_id, row in by_method[method].items():
            if question_id not in by_method["flat"]:
                continue
            this_right = 1.0 if row["correct"] else 0.0
            other_right = 1.0 if by_method["flat"][question_id]["correct"] else 0.0
            differences.append(this_right - other_right)
            tree_right.append(this_right == 1.0)
            flat_right.append(other_right == 1.0)
            if this_right and other_right:
                counts["both"] = counts["both"] + 1
            elif this_right:
                counts["tree"] = counts["tree"] + 1
            elif other_right:
                counts["flat"] = counts["flat"] + 1
            else:
                counts["neither"] = counts["neither"] + 1
        mean, low, high = paired_interval(differences, rng)
        only_tree, only_flat, p_value = mcnemar(tree_right, flat_right)
        comparisons.append({"method": method, "difference": mean, "ci_low": low,
                            "ci_high": high, "n": len(differences), "counts": counts,
                            "p_value": round(p_value, 4)})
        lines.append("| `%s` | %+.1f pts | [%+.1f, %+.1f] | %.3f%s | %d | %d | %d | %d |" % (
            method, 100 * mean, 100 * low, 100 * high, p_value,
            " **" if p_value < 0.05 else "",
            counts["both"], counts["tree"], counts["flat"], counts["neither"]))
    lines.append("")
    lines.append("The two middle columns are the real difference: questions one method answered "
                 "and the other did not. The rest were answered the same way by both.")

    (OUT_DIR / "quality_results.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    with open(OUT_DIR / "quality_results.json", "w", encoding="utf-8") as handle:
        json.dump({"summary": summary, "comparisons": comparisons}, handle, indent=1)
    log("wrote eval/bench/quality_results.md")


