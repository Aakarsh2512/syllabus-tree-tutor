"""A wider benchmark: normal RAG versus the RAPTOR tree, on eight documents.

Every document gets its own index, built from the same chunks three ways:

    flat       chunks only - ordinary RAG
    tree_ext   RAPTOR tree, extractive summaries (no model)
    tree_llm   RAPTOR tree, summaries written by the language model

Questions are generated by the language model from the documents, not written
by hand, and checked before use:

    specific   from one passage; its answer phrase must appear word for word
               in that passage
    broad      from four passages spread across the document; each key phrase
               must appear word for word in its passage, and the phrases must
               be spread over at least three chunks, so no single chunk can
               answer the question (the same check as eval/check_golden.py)

Metrics, at several context budgets (passages retrieved):

    specific   hit@k    - did any retrieved node contain the answer phrase
    broad      coverage - share of key phrases present in the retrieved text

A summary only gets credit for a phrase it contains word for word. Written
summaries paraphrase, so this under-credits the tree: the comparison is
conservative towards the paper's method.

Stages resume where they stopped, because the full run takes hours on a CPU:

    python eval/benchmark.py all            # everything, in order
    python eval/benchmark.py build-ext      # chunk + extractive trees (minutes)
    python eval/benchmark.py questions      # generate and check questions
    python eval/benchmark.py build-llm      # model-written trees (slow)
    python eval/benchmark.py run            # score whatever is built
"""

