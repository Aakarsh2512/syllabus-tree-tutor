def embedder():
    if _embedder["model"] is None:
        from sentence_transformers import SentenceTransformer
        _embedder["model"] = SentenceTransformer(config.EMBED_MODEL)
    return _embedder["model"]


def leaves_for(document_id: str) -> list[dict]:
    """The chunks of one document. Both trees are built from exactly these."""
    folder = BENCH_DATA / "single" / document_id
    folder.mkdir(parents=True, exist_ok=True)
    target = folder / (document_id + ".pdf")
    if not target.exists():
        target.write_bytes((PDF_DIR / (document_id + ".pdf")).read_bytes())
    return ingest.build_leaves(folder)


def build_variant(document: dict, variant: str) -> None:
    identifier = corpus_id(document["id"], variant)
    if store.index_exists(identifier):
        log("  " + identifier + " already built")
        return

    leaves = leaves_for(document["id"])
    provider = "offline" if variant in ["ext", "extfine"] else llm.provider()
    config.CLUSTER_TARGET_SIZE = 10 if variant == "extfine" else 0
    log("  building " + identifier + " from " + str(len(leaves)) + " chunks, summaries by " + provider)

    started = time.time()
    before = len(llm.fallbacks)

    def progress(message: str) -> None:
        if message.strip().startswith("summary"):
            log("    " + message.strip())

    nodes, embeddings = tree.build_tree(leaves, embedder(), progress=progress,
                                        use_provider=provider)
    stats = tree.tree_stats(nodes)
    meta = {
        "name": document["title"],
        "genre": document["genre"],
        "variant": variant,
        "summary_provider": provider,
        "leaf_chunks": len(leaves),
        "stats": stats,
        "build_seconds": round(time.time() - started, 1),
        "summary_fallbacks": len(llm.fallbacks) - before,
    }
    store.save_index(nodes, embeddings, meta, corpus_id=identifier)
    log("  built " + identifier + ": " + json.dumps(stats["nodes_per_level"])
        + " in " + str(meta["build_seconds"]) + "s"
        + (" (" + str(meta["summary_fallbacks"]) + " fallbacks)" if meta["summary_fallbacks"] else ""))


def build(variant: str) -> None:
    log("build " + variant)
    for document in load_manifest():
        build_variant(document, variant)


